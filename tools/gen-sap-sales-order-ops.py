import json, re, sys
spec = json.load(open(sys.argv[1]))
out = sys.argv[2]
def scope(m, p):
    if m == 'DELETE': return None, 'ไม่เปิด DELETE — ยกเลิกด้วย Rejection Reason แทน'
    if p == '/$batch': return None, 'ไม่เปิด $batch — ส่งทีละคำขอเพื่อให้ตรวจสิทธิ์และบันทึก audit ได้'
    if m == 'GET': return 'Read', None
    if p in ('/releaseApprovalRequest', '/rejectApprovalRequest'): return 'Approve', None
    if m == 'POST' and p == '/A_SalesOrder': return 'Create', None
    return 'Update', None
def cs(s): return '"' + s.replace('\\','\\\\').replace('"','\\"') + '"'
rows = []
for p, v in spec['paths'].items():
    for m in ('get','post','patch','delete'):
        if m not in v: continue
        op = v[m]; M = m.upper()
        sc, blocked = scope(M, p)
        coll = False
        if M == 'GET':
            sch = op['responses'].get('200',{}).get('content',{}).get('application/json',{}).get('schema',{})
            coll = 'results' in sch.get('properties',{}).get('d',{}).get('properties',{})
        summary = (op.get('summary') or '').strip()
        segs = [re.sub(r"^A_", "", re.sub(r"\(.*\)", "", x)) for x in p.strip('/').split('/')]
        audit = f"{M} " + '/'.join(segs)
        assert len(audit) <= 50, audit
        rows.append((M, p, sc, coll, summary, blocked, audit))
lines = []
for M,p,sc,coll,summary,blocked,audit in rows:
    s = f'SapScope.{sc}' if sc else 'null'
    b = cs(blocked) if blocked else 'null'
    lines.append(f'        new("{M}", {cs(p)}, {s}, {str(coll).lower()}, {cs(summary)}, {b}, {cs(audit)}),')
src = f'''// <auto-generated>
// สร้างจาก API_SALES_ORDER_SRV.json (SAP Business Accelerator Hub, Sales Order (A2X)) — {len(rows)} operations
// สร้างใหม่ด้วย tools/gen-sap-sales-order-ops.py เมื่อ SAP เพิ่ม/เปลี่ยน operation ห้ามแก้มือ
// </auto-generated>
namespace MGT.Portal.Api.Modules.Gateway;

public static partial class SapSalesOrderOperations
{{
    /// <summary>ทุก operation ของ API_SALES_ORDER_SRV: method, path ตาม spec, scope, เป็น collection หรือไม่, summary, เหตุผลที่ไม่เปิด, ชื่อใน audit log</summary>
    public static readonly IReadOnlyList<SapOperation> All =
    [
{chr(10).join(lines)}
    ];
}}
'''
open(out,'w',encoding='utf-8').write(src)
from collections import Counter
print(len(rows), Counter((r[0], r[2]) for r in rows), sum(1 for r in rows if r[5]))

# ---- OpenAPI ของ Gateway (สำหรับ MGT MCP และนักพัฒนา): ตัด operation ที่ไม่เปิด, ติด x-mgt-scope, ชี้ server ไปที่ Gateway ----
if len(sys.argv) > 3:
    import copy
    g = copy.deepcopy(spec)
    g['servers'] = [{'url': '/api/v1/sales/sap', 'description': 'MGT Gateway (Sandbox token → SAP DEV, Production token → SAP Production)'}]
    g['info']['title'] = 'MGT Gateway — SAP Sales Order (API_SALES_ORDER_SRV)'
    g['info']['description'] = ('เรียก SAP API_SALES_ORDER_SRV ผ่านโดเมนบริษัท ด้วย header X-Token-Id / X-Token-Secret (token หมวด Sales). '
        'คำขอเขียนต้องมี Idempotency-Key. ไม่เปิด DELETE และ $batch. x-mgt-scope บอกสิทธิ์ที่ต้องใช้.')
    comps = g.setdefault('components', {})
    comps['securitySchemes'] = {
        'TokenId': {'type': 'apiKey', 'in': 'header', 'name': 'X-Token-Id'},
        'TokenSecret': {'type': 'apiKey', 'in': 'header', 'name': 'X-Token-Secret'}}
    g['security'] = [{'TokenId': [], 'TokenSecret': []}]
    comps.setdefault('parameters', {})['IdempotencyKey'] = {
        'name': 'Idempotency-Key', 'in': 'header', 'required': True,
        'description': 'UUID ใหม่ทุกคำขอ ส่งค่าเดิมเมื่อ retry', 'schema': {'type': 'string', 'maxLength': 100}}
    scope_names = {'Read': 'sales.order.read', 'Create': 'sales.order.create', 'Update': 'sales.order.update', 'Approve': 'sales.order.approve'}
    for p in list(g['paths']):
        item = g['paths'][p]
        for m in ('get', 'post', 'patch', 'delete'):
            if m not in item: continue
            sc, blocked = scope(m.upper(), p)
            if blocked: del item[m]; continue
            op = item[m]
            op['x-mgt-scope'] = scope_names[sc]
            if m == 'patch': op['x-mgt-scope-note'] = 'ถ้า body มี SalesDocumentRjcnReason จะนับเป็น sales.order.cancel'
            if sc == 'Approve': op['x-mgt-disabled'] = 'ปิดไว้จนกว่าจะผูกกับ Flow อนุมัติ (Gateway:Sap:EnableApprove)'
            if m != 'get':
                op.setdefault('parameters', []).append({'$ref': '#/components/parameters/IdempotencyKey'})
            op.pop('security', None)
        if not any(k in item for k in ('get', 'post', 'patch')): del g['paths'][p]
    json.dump(g, open(sys.argv[3], 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    print('spec ops:', sum(1 for v in g['paths'].values() for k in v if k in ('get','post','patch')))
